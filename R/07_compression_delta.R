# Prompt 4, Step 3 -- the compressed-vs-uncompressed accuracy delta.
#
# Trains and evaluates two models on the SAME set of source recordings and
# the SAME train/val/test split (grouped_split() is deterministic given an
# identical source_file set, so both conditions get identical splits without
# any extra bookkeeping): one on WhatsApp-compressed audio (the main
# pipeline's data/processed/features.csv), one on uncompressed audio
# (resampled to the same 16kHz mono, but no Opus round-trip --
# data/processed_uncompressed/features.csv). The accuracy delta between them
# is the quantitative cost of using WhatsApp as the transport.
#
# NOTE ON STRUCTURE: 03_preprocess.R, 04_features.R, and 05_train.R each
# define their own top-level `main()` function (by design, so
# `Rscript R/0X_....R` works standalone) -- sourcing all three into one
# environment means each subsequent source() silently overwrites the
# previous file's `main`. This script captures each `main` into a
# distinctly-named variable immediately after sourcing, before the next
# source() call would clobber it.
#
# Usage:
#   Rscript R/07_compression_delta.R
#
# Requires data/processed/features.csv (the compressed condition) to
# already exist -- i.e. the normal pipeline has already been run once.

source(file.path("R", "utils.R"))
source(file.path("R", "02_codec_experiment.R"))  # WHATSAPP_SAMPLE_RATE, simulate_whatsapp_compression()

source(file.path("R", "03_preprocess.R"))
preprocess_main <- main  # capture before 04_features.R's source() overwrites `main`

source(file.path("R", "04_features.R"))
features_main <- main    # capture before 05_train.R's source() overwrites `main` again

source(file.path("R", "05_train.R"))
# 05_train.R's own `main()` writes fixed report/model files for the
# compressed condition -- not used here. We call grouped_split() and
# train_and_evaluate() directly on both conditions instead, for full
# control and so neither condition's files get overwritten by the other.

UNCOMPRESSED_PROCESSED_DIR    <- file.path("data", "processed_uncompressed")
UNCOMPRESSED_WINDOWS_MANIFEST <- file.path(UNCOMPRESSED_PROCESSED_DIR, "windows_manifest.csv")
UNCOMPRESSED_FEATURES_PATH    <- file.path(UNCOMPRESSED_PROCESSED_DIR, "features.csv")
DELTA_RESULTS_PATH            <- file.path("docs", "compression_delta.md")

main <- function() {
  if (!file.exists(FEATURES_PATH)) {
    stop(FEATURES_PATH, " not found -- run R/03_preprocess.R -> R/04_features.R -> ",
         "R/05_train.R first (the compressed condition).")
  }

  message("Building the UNCOMPRESSED condition (same sources, no Opus round-trip)...")
  preprocess_main(apply_compression = FALSE, processed_dir = UNCOMPRESSED_PROCESSED_DIR,
                   windows_manifest_path = UNCOMPRESSED_WINDOWS_MANIFEST)
  features_main(windows_manifest_path = UNCOMPRESSED_WINDOWS_MANIFEST,
                features_path = UNCOMPRESSED_FEATURES_PATH)

  compressed_features <- utils::read.csv(FEATURES_PATH, stringsAsFactors = FALSE)
  compressed_features <- grouped_split(compressed_features)
  compressed_result <- train_and_evaluate(compressed_features)

  uncompressed_features <- utils::read.csv(UNCOMPRESSED_FEATURES_PATH, stringsAsFactors = FALSE)
  uncompressed_features <- grouped_split(uncompressed_features)
  uncompressed_result <- train_and_evaluate(uncompressed_features)

  # Sanity check: the whole comparison is only fair if both conditions were
  # built from the same underlying source recordings. If this doesn't hold
  # (e.g. new data arrived between the two preprocessing runs), say so
  # loudly rather than silently reporting a misleading delta.
  same_sources <- setequal(unique(compressed_features$source_file),
                            unique(uncompressed_features$source_file))
  if (!same_sources) {
    warning("Compressed and uncompressed conditions were built from DIFFERENT ",
            "source file sets -- the accuracy delta below is not a clean ",
            "apples-to-apples comparison. Re-run both from the same data/raw ",
            "state before trusting this number.")
  }

  delta <- uncompressed_result$accuracy - compressed_result$accuracy

  ensure_dir(dirname(DELTA_RESULTS_PATH))
  lines <- c(
    "# Compression Delta: the Measured Cost of Using WhatsApp as the Transport",
    "",
    paste0("Generated by `R/07_compression_delta.R` on ", format(Sys.time(), "%Y-%m-%d %H:%M"),
           ". Both models trained/evaluated on the same source recordings and the ",
           "same grouped train/val/test split -- the only difference is whether the ",
           "test audio went through WhatsApp's Opus/Ogg compression before feature extraction."),
    "",
    if (!same_sources) paste0(
      "**WARNING: the two conditions were built from different source-file sets.** ",
      "See the warning emitted by this script -- treat the delta below with caution."
    ) else "Source-file sets for both conditions confirmed identical.",
    "",
    sprintf("- **Compressed (WhatsApp-simulated) test accuracy: %s** (%d test source files)",
            if (is.na(compressed_result$accuracy)) "N/A" else scales_percent(compressed_result$accuracy),
            compressed_result$n_test_sources),
    sprintf("- **Uncompressed test accuracy: %s** (%d test source files)",
            if (is.na(uncompressed_result$accuracy)) "N/A" else scales_percent(uncompressed_result$accuracy),
            uncompressed_result$n_test_sources),
    sprintf("- **Delta (uncompressed minus compressed): %s**",
            if (is.na(delta)) "N/A" else scales_percent(delta)),
    "",
    "## Reading this number",
    "",
    "A positive delta means compression cost accuracy (uncompressed did ",
    "better); a delta near zero means the classifier's feature set is robust ",
    "to WhatsApp's lossy encoding for these classes; a negative delta would ",
    "mean the compressed model did *better* on its own held-out test set, ",
    "which can happen with small test sets and should not be over-interpreted ",
    "as compression *helping*.",
    "",
    "## Interpretation",
    "",
    "TBD -- fill in after reading the numbers above, with the same honesty ",
    "standard as the rest of this project: small test-set sizes mean this ",
    "delta has real uncertainty around it, not a precise measurement."
  )
  writeLines(lines, DELTA_RESULTS_PATH)

  message(sprintf("Compression delta: %s (compressed) vs %s (uncompressed) = %s delta. Written to %s",
                   if (is.na(compressed_result$accuracy)) "N/A" else scales_percent(compressed_result$accuracy),
                   if (is.na(uncompressed_result$accuracy)) "N/A" else scales_percent(uncompressed_result$accuracy),
                   if (is.na(delta)) "N/A" else scales_percent(delta),
                   DELTA_RESULTS_PATH))

  invisible(list(compressed = compressed_result, uncompressed = uncompressed_result, delta = delta))
}

if (sys.nframe() == 0) {
  main()
}
